-- Apply as the application schema owner. Tested for Oracle Database 19c+.
CREATE TABLE regions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    country VARCHAR2(80 CHAR) DEFAULT 'India' NOT NULL
);

CREATE TABLE roles (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(30 CHAR) NOT NULL UNIQUE
);

CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(255 CHAR) NOT NULL UNIQUE,
    full_name VARCHAR2(160 CHAR) NOT NULL,
    hashed_password VARCHAR2(255 CHAR) NOT NULL,
    role_id NUMBER NOT NULL REFERENCES roles(id),
    is_active NUMBER(1) DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1))
);

CREATE TABLE merchants (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR2(32 CHAR) NOT NULL UNIQUE,
    name VARCHAR2(180 CHAR) NOT NULL,
    category VARCHAR2(80 CHAR) NOT NULL,
    region_id NUMBER NOT NULL REFERENCES regions(id),
    status VARCHAR2(20 CHAR) DEFAULT 'active' NOT NULL CHECK (status IN ('active', 'dormant')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE transactions (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER NOT NULL REFERENCES merchants(id),
    transaction_ref VARCHAR2(48 CHAR) NOT NULL UNIQUE,
    occurred_at TIMESTAMP NOT NULL,
    amount NUMBER(16, 2) NOT NULL CHECK (amount >= 0),
    status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('successful', 'failed', 'pending')),
    channel VARCHAR2(30 CHAR) NOT NULL
);

CREATE TABLE collections (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER NOT NULL REFERENCES merchants(id),
    transaction_id NUMBER REFERENCES transactions(id),
    collected_at TIMESTAMP NOT NULL,
    amount NUMBER(16, 2) NOT NULL CHECK (amount >= 0),
    status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('successful', 'failed', 'pending'))
);

CREATE TABLE disbursements (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER NOT NULL REFERENCES merchants(id),
    disbursed_at TIMESTAMP NOT NULL,
    amount NUMBER(16, 2) NOT NULL CHECK (amount >= 0),
    status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('successful', 'failed', 'pending')),
    reference VARCHAR2(48 CHAR) NOT NULL UNIQUE
);

CREATE TABLE subscribers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER NOT NULL REFERENCES merchants(id),
    subscriber_ref VARCHAR2(48 CHAR) NOT NULL UNIQUE,
    joined_at DATE NOT NULL,
    status VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('active', 'inactive'))
);

CREATE TABLE forecast_results (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER REFERENCES merchants(id),
    target_date DATE NOT NULL,
    model_name VARCHAR2(40 CHAR) NOT NULL,
    predicted_revenue NUMBER(16, 2) NOT NULL,
    lower_bound NUMBER(16, 2) NOT NULL,
    upper_bound NUMBER(16, 2) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_forecast_bounds CHECK (lower_bound <= upper_bound)
);

CREATE TABLE anomaly_results (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id NUMBER NOT NULL REFERENCES merchants(id),
    detected_at TIMESTAMP NOT NULL,
    metric VARCHAR2(40 CHAR) NOT NULL,
    observed_value NUMBER(16, 2) NOT NULL,
    severity VARCHAR2(20 CHAR) NOT NULL,
    method VARCHAR2(40 CHAR) NOT NULL,
    details CLOB NOT NULL,
    CONSTRAINT uq_anomaly_signal UNIQUE (merchant_id, detected_at, metric, method)
);

CREATE INDEX ix_users_role ON users(role_id);
CREATE INDEX ix_merchants_region ON merchants(region_id);
CREATE INDEX ix_transactions_date ON transactions(occurred_at);
CREATE INDEX ix_tx_merchant_date ON transactions(merchant_id, occurred_at);
CREATE INDEX ix_tx_status_date ON transactions(status, occurred_at);
CREATE INDEX ix_collections_merchant ON collections(merchant_id);
CREATE INDEX ix_collections_date ON collections(collected_at);
CREATE INDEX ix_disbursements_merchant ON disbursements(merchant_id);
CREATE INDEX ix_disbursements_date ON disbursements(disbursed_at);
CREATE INDEX ix_subscribers_merchant ON subscribers(merchant_id);
CREATE INDEX ix_forecast_merchant_date ON forecast_results(merchant_id, target_date);
CREATE INDEX ix_anomaly_merchant_date ON anomaly_results(merchant_id, detected_at);

CREATE OR REPLACE VIEW vw_merchant_revenue AS
SELECT m.id merchant_id, m.code merchant_code, m.name merchant_name,
       r.name region_name, COUNT(t.id) successful_transactions,
       NVL(SUM(t.amount), 0) total_revenue
FROM merchants m
JOIN regions r ON r.id = m.region_id
LEFT JOIN transactions t ON t.merchant_id = m.id AND t.status = 'successful'
GROUP BY m.id, m.code, m.name, r.name;

CREATE OR REPLACE VIEW vw_daily_financials AS
SELECT activity_date, SUM(revenue) revenue, SUM(collections) collections, SUM(disbursements) disbursements
FROM (
    SELECT TRUNC(occurred_at) activity_date,
           SUM(CASE WHEN status = 'successful' THEN amount ELSE 0 END) revenue,
           CAST(0 AS NUMBER(16, 2)) collections, CAST(0 AS NUMBER(16, 2)) disbursements
    FROM transactions GROUP BY TRUNC(occurred_at)
    UNION ALL
    SELECT TRUNC(collected_at), 0,
           SUM(CASE WHEN status = 'successful' THEN amount ELSE 0 END), 0
    FROM collections GROUP BY TRUNC(collected_at)
    UNION ALL
    SELECT TRUNC(disbursed_at), 0, 0,
           SUM(CASE WHEN status = 'successful' THEN amount ELSE 0 END)
    FROM disbursements GROUP BY TRUNC(disbursed_at)
)
GROUP BY activity_date;

CREATE OR REPLACE PROCEDURE prc_purge_anomaly_results (
    p_older_than_days IN NUMBER,
    p_deleted_count OUT NUMBER
) AS
BEGIN
    IF p_older_than_days < 1 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Retention period must be at least one day');
    END IF;
    DELETE FROM anomaly_results WHERE detected_at < SYSTIMESTAMP - NUMTODSINTERVAL(p_older_than_days, 'DAY');
    p_deleted_count := SQL%ROWCOUNT;
END;
/

CREATE OR REPLACE PROCEDURE prc_purge_old_forecast_results (
    p_older_than_days IN NUMBER,
    p_deleted_count OUT NUMBER
) AS
BEGIN
    IF p_older_than_days < 1 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Retention period must be at least one day');
    END IF;
    DELETE FROM forecast_results WHERE created_at < SYSTIMESTAMP - NUMTODSINTERVAL(p_older_than_days, 'DAY');
    p_deleted_count := SQL%ROWCOUNT;
END;
